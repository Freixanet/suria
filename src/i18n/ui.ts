/** Traductor d'una llengua, amb substitució de {variables}. */
export function traductor(llengua: Llengua) {
  return (clau: Clau, vars: Record<string, string> = {}) =>
    ui[llengua][clau].replace(/\{(\w+)\}/g, (_, nom: string) => vars[nom] ?? `{${nom}}`);
}
